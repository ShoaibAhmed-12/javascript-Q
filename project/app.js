/* =========================================================
   QUESTION GENERATOR
========================================================= */

function createChapter(title, topics) {

    const shortQuestions = [
        {
            q: `What is ${topics[0]}?`,
            a: `${topics[0]} is an important concept studied in ${title}.`
        },
        {
            q: `Define ${topics[1]}.`,
            a: `${topics[1]} refers to an important principle or concept related to ${title}.`
        },
        {
            q: `What is the importance of ${topics[2]}?`,
            a: `${topics[2]} is important because it helps explain important processes and relationships in ${title}.`
        },
        {
            q: `Explain briefly the role of ${topics[3]}.`,
            a: `${topics[3]} plays an important role in understanding the concepts covered in ${title}.`
        },
        {
            q: `What do you understand by ${topics[4]}?`,
            a: `${topics[4]} is a key concept associated with ${title}.`
        },
        {
            q: `Why is ${topics[5]} important?`,
            a: `${topics[5]} is important because it is used to explain or understand important scientific observations related to ${title}.`
        },
        {
            q: `Define ${topics[6]}.`,
            a: `${topics[6]} is a fundamental term related to ${title}.`
        },
        {
            q: `What is the significance of ${topics[7]}?`,
            a: `${topics[7]} has an important role in the study and understanding of ${title}.`
        }
    ];


    const longQuestions = [
        {
            q: `Explain ${topics[0]} in detail.`,
            a: `${topics[0]} is an important part of ${title}. It should be understood through its definition, characteristics, applications and relationship with other concepts in the chapter.`
        },
        {
            q: `Discuss ${topics[1]} and its importance.`,
            a: `${topics[1]} is an important concept in ${title}. Its study helps students understand the underlying scientific principles, observations and applications associated with this topic.`
        },
        {
            q: `Explain the relationship between ${topics[2]} and ${topics[3]}.`,
            a: `${topics[2]} and ${topics[3]} are related concepts in ${title}. Understanding their relationship helps explain how the relevant scientific process or phenomenon works.`
        },
        {
            q: `Write a detailed note on ${topics[4]}.`,
            a: `${topics[4]} is an important topic in ${title}. A complete explanation includes its meaning, important characteristics, scientific significance and relevant examples or applications.`
        }
    ];


    const mcqTopics = [
        topics[0],
        topics[1],
        topics[2],
        topics[3],
        topics[4],
        topics[5],
        topics[6],
        topics[7],
        topics[0],
        topics[1],
        topics[2],
        topics[3],
        topics[4],
        topics[5],
        topics[6]
    ];


    const mcqs = mcqTopics.map((topic, index) => {

        const options = [
            topic,
            topics[(index + 1) % topics.length],
            topics[(index + 2) % topics.length],
            topics[(index + 3) % topics.length]
        ];

        return {
            question: `Which of the following is directly associated with ${title}?`,
            options: options,
            answer: topic
        };
    });


    return {
        title: title,
        shortQuestions: shortQuestions,
        longQuestions: longQuestions,
        mcqs: mcqs
    };
}


